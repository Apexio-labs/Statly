/** Writes the JSON Schemas and Python types that the add-on loads at runtime. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { aiErrorCodes, aiPages, aiProviderDefaults, aiSettingKeys } from "../src/ai.ts";
import { aiStatistics, aiTools, aiWidgetGuide } from "../src/aiTools.ts";
import { builtinWidgets, defaultLayout, defaultSettings } from "../src/dashboard.ts";
import {
  goalViews,
  goalWidgetPrefix,
  goalWidgetSizes,
  maxGoals,
  streakMilestones,
} from "../src/goals.ts";
import { deviceColumns, gridColumns, widgetSizeLimits } from "../src/limits.ts";
import { maxChanges, permissionRules } from "../src/permissions.ts";
import { errorCodes, events, methods } from "../src/rpc.ts";

type JsonSchema = {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
};

const here = dirname(fileURLToPath(import.meta.url));
const output = resolve(here, "../../../addon/src/statly/contract");

function toSchema(type: z.ZodType): JsonSchema {
  const { $schema: _dropped, ...schema } = z.toJSONSchema(type) as JsonSchema & {
    $schema?: string;
  };
  return schema;
}

function pascalCase(name: string): string {
  return name
    .split(/[._]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const declarations: string[] = [];

/** A value as Python writes it in a `Literal`: booleans are `True` and `False` there. */
function pythonLiteral(value: unknown): string {
  return typeof value === "boolean" ? (value ? "True" : "False") : JSON.stringify(value);
}

function pythonType(schema: JsonSchema, name: string): string {
  const options = schema.anyOf ?? schema.oneOf;
  if (options) {
    return options.map((option, index) => pythonType(option, `${name}Option${index}`)).join(" | ");
  }
  if (schema.enum) {
    return `Literal[${schema.enum.map(pythonLiteral).join(", ")}]`;
  }
  if (schema.const !== undefined) {
    return `Literal[${pythonLiteral(schema.const)}]`;
  }
  switch (schema.type) {
    case "string":
      return "str";
    case "integer":
      return "int";
    case "number":
      return "float";
    case "boolean":
      return "bool";
    case "null":
      return "None";
    case "array":
      return `list[${pythonType(schema.items ?? {}, `${name}Item`)}]`;
    case "object":
      return pythonClass(schema, name);
    default:
      return "Any";
  }
}

function pythonClass(schema: JsonSchema, name: string): string {
  const required = new Set(schema.required ?? []);
  const fields = Object.entries(schema.properties ?? {}).map(([key, value]) => {
    const fieldType = pythonType(value, `${name}${pascalCase(key)}`);
    return `    ${key}: ${required.has(key) ? fieldType : `NotRequired[${fieldType}]`}`;
  });
  declarations.push(`class ${name}(TypedDict):\n${fields.join("\n") || "    pass"}\n`);
  return name;
}

const rpc = {
  methods: Object.fromEntries(
    Object.entries(methods).map(([name, method]) => [
      name,
      { params: toSchema(method.params), result: toSchema(method.result) },
    ]),
  ),
  events: Object.fromEntries(
    Object.entries(events).map(([name, payload]) => [name, toSchema(payload)]),
  ),
  errorCodes,
  grid: {
    columns: gridColumns,
    deviceColumns,
    widgets: builtinWidgets,
    customWidgetLimits: widgetSizeLimits,
    defaultLayout,
  },
  defaultSettings,
  permissions: { rules: permissionRules, maxChanges },
  goals: {
    prefix: goalWidgetPrefix,
    views: goalViews,
    sizes: goalWidgetSizes,
    maxGoals,
    milestones: streakMilestones,
  },
  ai: {
    providers: aiProviderDefaults,
    settingKeys: aiSettingKeys,
    errorCodes: aiErrorCodes,
    statistics: aiStatistics,
    widgetGuide: aiWidgetGuide,
    pages: aiPages,
    tools: Object.fromEntries(
      Object.entries(aiTools).map(([name, tool]) => [
        name,
        {
          access: tool.access,
          description: tool.description,
          method: tool.method,
          permission: tool.permission ?? null,
          input: toSchema(tool.input),
          shown: toSchema(tool.shown ?? tool.input),
        },
      ]),
    ),
  },
};

for (const [name, method] of Object.entries(rpc.methods)) {
  pythonType(method.params, `${pascalCase(name)}Params`);
  pythonType(method.result, `${pascalCase(name)}Result`);
}
for (const [name, payload] of Object.entries(rpc.events)) {
  pythonType(payload, `${pascalCase(name)}Payload`);
}

const pythonModule = `"""Generated by packages/contract. Do not edit by hand."""

from __future__ import annotations

from typing import Any, Literal, NotRequired, TypedDict

__all__ = ["Any", "Literal", "NotRequired", "TypedDict"]


${declarations.join("\n\n")}`;

mkdirSync(output, { recursive: true });
writeFileSync(resolve(output, "rpc.schema.json"), `${JSON.stringify(rpc, null, 2)}\n`);
writeFileSync(resolve(output, "types.py"), pythonModule);
